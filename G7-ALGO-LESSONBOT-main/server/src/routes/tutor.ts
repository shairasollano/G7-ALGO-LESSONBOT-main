/**
 * Tutor chat routes. Two responsibilities live here and nowhere else:
 *   - Conversation flow: SSE framing, honest mode declaration, duplicate-free
 *     delivery, cancellation on client disconnect.
 *   - The request-to-solver-to-render pipeline: validated plan (Gemini) or
 *     keyword intent (curated) may ask for a deterministic solver run; the
 *     trace is emitted as structured blocks; prose deltas stream as they are
 *     produced; actions derive from what the producer can truly do next.
 *
 * SSE protocol (single, explicit):
 *   event: start   data: { requestId, topicId, level, computed }
 *   event: meta    data: { mode, topicId, effectiveTopicId, level, computed }
 *                  — topicId is the requested selection; effectiveTopicId the
 *                    topic that actually governs the answer (message wins).
 *   event: delta   data: { text }    — newly generated text ONLY.
 *   event: block   data: { index, block } — structured educational block.
 *   event: done    data: { requestId, usage?, actions?, effectiveTopicId? }
 *                  — metadata only; usage.outputTokens is exact when the
 *                    provider reports it. No text payload.
 *   event: error   data: { message } — safe, user-presentable error.
 */
import { Router } from "express";
import { chatRequestSchema } from "../schemas/index.js";
import { generateWithFallback, streamWithFallback } from "../services/ai/index.js";
import { getTopic } from "../data/topics.js";
import { traceFromResult, resolveComputation } from "../services/algorithms/curated-examples.js";
import { runSolver } from "../services/algorithms/registry.js";
import { storeQuiz } from "../services/quizzes/store.js";
import { availableCuratedActions } from "../services/ai/curated-fallback.js";
import { config } from "../config.js";
import { rateLimiter } from "../middleware/rate-limit.js";
import type { SolverResult } from "../../../shared/contract.js";

export const tutorRouter = Router();

/** Run the matched deterministic solver once for a request (keyword path). */
function computeIfNeeded(
  message: string,
  topicId: string | null,
): SolverResult | undefined {
  const intent = resolveComputation(message, topicId);
  if (!intent) return undefined;
  return runSolver(intent.example.solverId, intent.example.input);
}

const GEMINI_ACTIONS = ["explain_simpler", "formal_proof", "another_example", "quiz", "compare"];

function verifiedTraceBlocks(result: SolverResult) {
  return [
    {
      type: "text" as const,
      markdown: `**Verified computation** (${result.algorithmName}). Every value below is computed by the app's deterministic solver — not generated by the AI.`,
    },
    { type: "algorithm_trace" as const, trace: traceFromResult(result) },
  ];
}

tutorRouter.post("/api/tutor/chat", rateLimiter(config.ai.rateLimit.windowMs, config.ai.rateLimit.maxRequests), async (req, res, next) => {
  try {
    const body = chatRequestSchema.parse(req.body);
    const topic = getTopic(body.topicId ?? "polynomial-reductions");
    if (!topic) {
      res.status(404).json({
        error: {
          code: "topic_not_found",
          message: `No topic with id "${body.topicId}". Pick one from GET /api/topics.`,
        },
      });
      return;
    }

    const result = computeIfNeeded(body.message, body.topicId ?? null);
    const verdict = await generateWithFallback({
      message: body.message,
      topicId: body.topicId ?? null,
      level: body.level,
      history: body.history ?? [],
      computedTrace: result
        ? {
            algorithmId: result.algorithmId,
            algorithmName: result.algorithmName,
            result: result.result,
            guarantee: result.guarantee,
          }
        : undefined,
    });

    const computation = verdict.computation ?? result;
    const effectiveTopicId = verdict.effectiveTopicId;
    const history = body.history ?? [];
    const actions =
      verdict.mode === "ai"
        ? GEMINI_ACTIONS
        : availableCuratedActions({ history }, effectiveTopicId);

    let blocks = verdict.blocks;
    if (computation) {
      blocks = [...verifiedTraceBlocks(computation), ...blocks];
    }

    for (const block of blocks) {
      if (block.type === "quiz") {
        storeQuiz(block.quiz);
      }
    }

    res.json({
      blocks,
      mode: verdict.mode,
      topicId: body.topicId ?? null,
      effectiveTopicId,
      level: body.level,
      computed: Boolean(computation),
      actions,
    });
  } catch (err) {
    next(err);
  }
});

/**
 * SSE streaming endpoint: real incremental streaming.
 *   - The AI provider forwards model text deltas as they arrive.
 *   - The curated provider is not a generative model: it sends its structured
 *     blocks directly and is honestly labeled. It never fakes token pacing.
 *   - Client disconnects abort the provider request where supported.
 */
tutorRouter.post("/api/tutor/chat/stream", rateLimiter(config.ai.rateLimit.windowMs, config.ai.rateLimit.maxRequests), async (req, res, next) => {
  try {
    const body = chatRequestSchema.parse(req.body);
    const topic = getTopic(body.topicId ?? "polynomial-reductions");
    if (!topic) {
      res.status(404).json({ error: { code: "topic_not_found", message: `No topic with id "${body.topicId}".` } });
      return;
    }

    const keywordResult = computeIfNeeded(body.message, body.topicId ?? null);
    const requestId = `r-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;

    res.setHeader("Content-Type", "text/event-stream");
    res.setHeader("Cache-Control", "no-cache");
    res.setHeader("Connection", "keep-alive");
    res.setHeader("X-Accel-Buffering", "no");
    res.flushHeaders();

    // Session state — guards against writing after the stream is finished
    // (error or client disconnect) so nothing can be duplicated or appended
    // past its intended place.
    let finished = false;
    let metaSent = false;
    let blockIndex = 0;
    // Effective topic, resolved by the provider before the first delta.
    let declaredEffectiveTopic: string | null = null;

    const sendEvent = (event: string, data: unknown) => {
      if (finished || res.writableEnded) return;
      res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`);
    };

    const finish = () => {
      if (finished) return;
      finished = true;
      if (!res.writableEnded) res.end();
    };

    // Cancellation: when the client disconnects mid-stream (the response
    // closes before it was fully written), abort the provider request and
    // stop. No synthetic events are sent to a dead socket. Note: listening on
    // `req` would misfire because the request stream "closes" as soon as the
    // body has been fully parsed.
    const abortController = new AbortController();
    let clientGone = false;
    res.on("close", () => {
      if (!res.writableEnded) {
        clientGone = true;
        abortController.abort();
        finish();
      }
    });

    const finishWithError = (message: string) => {
      sendEvent("error", { message });
      finish();
    };

    try {
      sendEvent("start", { requestId, topicId: body.topicId ?? null, level: body.level, computed: Boolean(keywordResult) });

      const outcome = await streamWithFallback(
        {
          message: body.message,
          topicId: body.topicId ?? null,
          level: body.level,
          history: body.history ?? [],
          computedTrace: keywordResult
            ? {
                algorithmId: keywordResult.algorithmId,
                algorithmName: keywordResult.algorithmName,
                result: keywordResult.result,
                guarantee: keywordResult.guarantee,
              }
            : undefined,
        },
        {
          signal: abortController.signal,
          onResolved: ({ effectiveTopicId }) => {
            if (finished || clientGone || metaSent) return;
            // Resolved before the first delta: the mode is still provisional —
            // resolved() fires for both providers, so only the producing mode
            // stays unknown until deltas exist, but the effective topic is
            // already final and worth declaring early.
            declaredEffectiveTopic = effectiveTopicId;
          },
          onDelta: (text) => {
            if (finished || clientGone) return;
            // The producing mode becomes conclusively "AI" the moment a real
            // text delta exists.
            if (!metaSent) {
              metaSent = true;
              sendEvent("meta", { mode: "ai", topicId: body.topicId ?? null, effectiveTopicId: declaredEffectiveTopic, level: body.level, computed: true });
            }
            sendEvent("delta", { text });
          },
        },
      );

      if (clientGone) return;

      // No deltas streamed (curated provider, or AI failed before output):
      // declare the honest producing mode before any block arrives.
      if (!metaSent) {
        metaSent = true;
        sendEvent("meta", {
          mode: outcome.reply.mode,
          topicId: body.topicId ?? null,
          effectiveTopicId: outcome.effectiveTopicId,
          level: body.level,
          computed: Boolean(outcome.computation ?? keywordResult),
        });
      }

      const computation = outcome.computation ?? keywordResult;

      // The assembled reply continues from streamed deltas; when deltas were
      // streamed, the assembled markdown equals what the client already has,
      // so we must NOT re-send it. Structured blocks (verified trace) and any
      // remaining metadata are still delivered.
      if (computation) {
        for (const block of verifiedTraceBlocks(computation)) {
          sendEvent("block", { index: blockIndex++, block });
        }
      }

      // When NO deltas were streamed (curated path), deliver the reply as
      // structured blocks — that is the curated provider's native output.
      if (!outcome.streamedDeltas) {
        for (const block of outcome.reply.blocks) {
          if (block.type === "quiz") storeQuiz(block.quiz);
          if ((!computation || block.type !== "algorithm_trace") && !isTraceLeadText(block, computation)) {
            sendEvent("block", { index: blockIndex++, block });
          }
        }
      } else {
        // The prose already reached the student as deltas. Anything the
        // provider returned that is NOT that prose — a guardrail correction
        // block appended after screening — is still new information and has
        // to be delivered.
        for (const block of outcome.reply.blocks) {
          if (block.type === "quiz") storeQuiz(block.quiz);
          if (block.type !== "text") {
            sendEvent("block", { index: blockIndex++, block });
          }
        }
      }

      // Contextual actions: derived from what the producing provider can truly
      // honor next (Gemini can fulfill all; curated is availability-checked,
      // e.g. "another example" disappears once every topic example is shown).
      sendEvent("done", {
        requestId,
        effectiveTopicId: outcome.effectiveTopicId,
        ...(outcome.usage ? { usage: outcome.usage } : {}),
        ...(outcome.fallbackReason ? { fallbackReason: outcome.fallbackReason } : {}),
        actions:
          outcome.reply.mode === "ai"
            ? GEMINI_ACTIONS
            : availableCuratedActions({ history: body.history ?? [] }, outcome.effectiveTopicId),
      });
      finish();
    } catch (err) {
      if (clientGone) return;
      finishWithError(friendlyStreamError(err));
    }
  } catch (err) {
    next(err);
  }
});

/** A curated text block that merely leads into the trace block (dedup guard). */
function isTraceLeadText(
  block: import("../../../shared/contract.js").ChatBlock,
  computation: SolverResult | undefined,
): boolean {
  return (
    Boolean(computation) &&
    block.type === "text" &&
    typeof block.markdown === "string" &&
    /^\*\*Verified computation\*\*/.test(block.markdown)
  );
}

function friendlyStreamError(err: unknown): string {
  if (err instanceof Error) {
    if (err.name === "AbortError") return "Generation was stopped.";
    if (err.name === "BlockedContentError" || err.message.includes("blocked content")) {
      return "The AI response was rejected by a safety check before it reached you. Please try again.";
    }
    if (err.message.includes("timed out")) return "The AI request timed out. Please try again.";
    if (
      err.message.includes("provider failed") &&
      !(err.message.includes("empty stream") || err.message.includes("exceeded"))
    ) {
      return "The AI provider encountered an error. Please try again.";
    }
    if (err.message.includes("empty stream")) return "The AI provider returned an empty response. Please try again.";
    if (err.message.includes("exceeded")) return "The AI response was too long and was stopped. Please rephrase your question.";
    return "Something went wrong. Please try again.";
  }
  return "Something went wrong. Please try again.";
}
